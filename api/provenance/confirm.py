def _entity_edges_for(db: Session, wid: str) -> list[Edge]:
    """Entity edges for one work, exactly as build_graph.py derives them."""
    edges: list[Edge] = []
    wn = work_node(wid)
    for aid, deg in db.execute(text(
        "SELECT wa.author_id, a.corpus_degree FROM work_authors wa "
        "JOIN authors a ON a.id = wa.author_id WHERE wa.work_id = :w"),
            {"w": wid}).all():
        an = f"BA{aid[1:]}" if aid.startswith("A") else f"BA{aid}"
        edges.append(Edge(wn, an, W["authored_by"], "author", "authored_by"))
        edges.append(Edge(an, wn, W["wrote"] * damp(deg), "author", "wrote"))
    max_idf = db.execute(text(
        "SELECT coalesce(max(idf), 1.0) FROM topics")).scalar_one() or 1.0
    for tid, deg, idf in db.execute(text(
        "SELECT wt.topic_id, t.corpus_degree, t.idf FROM work_topics wt "
        "JOIN topics t ON t.id = wt.topic_id WHERE wt.work_id = :w"),
            {"w": wid}).all():
        tn = f"BT{tid[1:]}" if tid.startswith("T") else f"BT{tid}"
        scale = (idf or 0.0) / max_idf
        edges.append(Edge(wn, tn, W["tagged"] * scale, "topic", "tagged"))
        edges.append(Edge(tn, wn, W["tags"] * scale * damp(deg), "topic", "tags"))
    row = db.execute(text(
        "SELECT w.venue_id, v.corpus_degree FROM works w "
        "JOIN venues v ON v.id = w.venue_id "
        "WHERE w.id = :w AND w.venue_id IS NOT NULL"), {"w": wid}).first()
    if row:
        vid, deg = row
        vn = f"BS{vid[1:]}" if vid.startswith("S") else f"BS{vid}"
        edges.append(Edge(wn, vn, W["published_in"], "venue", "published_in"))
        edges.append(Edge(vn, wn, W["publishes"] * damp(deg), "venue", "publishes"))
    for iid, deg in db.execute(text(
        "SELECT wi.institution_id, i.corpus_degree FROM work_institutions wi "
        "JOIN institutions i ON i.id = wi.institution_id WHERE wi.work_id = :w"),
            {"w": wid}).all():
        inn = f"BI{iid[1:]}" if iid.startswith("I") else f"BI{iid}"
        edges.append(Edge(wn, inn, W["affiliated"], "institution", "affiliated"))
        edges.append(Edge(inn, wn, W["hosts"] * damp(deg), "institution", "hosts"))
    return edges


def _persist_edges(db: Session, edges: list[Edge]) -> None:
    """Max-weight-wins on (src, dst, context) collisions -- the same rule
    build_graph.dedupe() applies at rebuild time (an uploaded citation can
    collide with an existing couples/co_cited edge; the deliberate citation
    must not lose to the weaker detector). The engine push reads the table
    back afterwards, so engine and graph_edges always hold the same weight."""
    if not edges:
        return
    db.execute(
        text("INSERT INTO graph_edges (src, dst, weight, context, relation) "
             "VALUES (:src, :dst, :w, :ctx, :rel) "
             "ON CONFLICT (src, dst, context) DO UPDATE SET "
             " weight = GREATEST(graph_edges.weight, EXCLUDED.weight), "
             " relation = CASE WHEN EXCLUDED.weight > graph_edges.weight "
             "   THEN EXCLUDED.relation ELSE graph_edges.relation END"),
        [{"src": e.src, "dst": e.dst, "w": e.weight, "ctx": e.context,
          "rel": e.relation} for e in edges],
    )


