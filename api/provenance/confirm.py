def _reconstruct_abstract(inv: dict | None) -> str | None:
    if not inv:
        return None
    positions = [(i, w) for w, idxs in inv.items() for i in idxs]
    if not positions:
        return None
    positions.sort()
    return " ".join(w for _, w in positions)[:8000]


def materialise_openalex_work(db: Session, oa: OpenAlex, oa_id: str) -> str | None:
    """Create a full corpus works row (+ entity rows and links) from OpenAlex.
    Ordinary corpus record: source='openalex' (spec Visibility: only UL...
    locals are labelled). Returns the work id, or None if OpenAlex cannot
    supply the record right now."""
    existing = db.get(Work, oa_id)
    if existing is not None:
        return oa_id
    try:
        w = oa.get(f"works/{oa_id}")
    except OpenAlexUnavailable:
        return None
    if not w:
        return None

    venue_id = None
    loc = (w.get("primary_location") or {}).get("source") or {}
    if loc.get("id"):
        venue_id = short_id(loc["id"])
        db.execute(text(
            "INSERT INTO venues (id, display_name, type, issn_l, publisher, corpus_degree) "
            "VALUES (:i, :n, :t, :issn, :p, 0) ON CONFLICT (id) DO NOTHING"),
            {"i": venue_id, "n": loc.get("display_name"),
             "t": (loc.get("type") or "")[:32] or None,
             "issn": (loc.get("issn_l") or "")[:16] or None,
             "p": loc.get("host_organization_name")})

    db.execute(text(
        "INSERT INTO works (id, title, abstract, year, publication_date, "
        " cited_by_count, doi, type, language, is_oa, is_stub, venue_id, "
        " ref_count, in_corpus_cited_by, source) "
        "VALUES (:id, :title, :abstract, :year, CAST(:pdate AS date), :cited, :doi, :type, "
        " :lang, :oa, false, :venue, 0, 0, 'openalex') "
        "ON CONFLICT (id) DO NOTHING"),
        {"id": oa_id, "title": w.get("title") or w.get("display_name"),
         "abstract": _reconstruct_abstract(w.get("abstract_inverted_index")),
         "year": w.get("publication_year"),
         "pdate": w.get("publication_date"),
         "cited": int(w.get("cited_by_count") or 0),
         "doi": w.get("doi"), "type": (w.get("type") or "")[:48] or None,
         "lang": (w.get("language") or "")[:8] or None,
         "oa": bool((w.get("open_access") or {}).get("is_oa")),
         "venue": venue_id})

    for pos, auth in enumerate(w.get("authorships") or []):
        a = auth.get("author") or {}
        aid = short_id(a.get("id"))
        if not aid:
            continue
        db.execute(text(
            "INSERT INTO authors (id, display_name, works_count, cited_by_count, "
            " orcid, corpus_degree) VALUES (:i, :n, 0, 0, :o, 0) "
            "ON CONFLICT (id) DO NOTHING"),
            {"i": aid, "n": a.get("display_name"), "o": a.get("orcid")})
        db.execute(text(
            "INSERT INTO work_authors (work_id, author_id, position) "
            "VALUES (:w, :a, :p) ON CONFLICT DO NOTHING"),
            {"w": oa_id, "a": aid, "p": pos})
        db.execute(text(
            "UPDATE authors SET corpus_degree = corpus_degree + 1 WHERE id = :a"),
            {"a": aid})
        for inst in auth.get("institutions") or []:
            iid = short_id(inst.get("id"))
            if not iid:
                continue
            db.execute(text(
                "INSERT INTO institutions (id, display_name, ror, country_code, "
                " corpus_degree) VALUES (:i, :n, :r, :c, 0) "
                "ON CONFLICT (id) DO NOTHING"),
                {"i": iid, "n": inst.get("display_name"), "r": inst.get("ror"),
                 "c": (inst.get("country_code") or "")[:8] or None})
            db.execute(text(
                "INSERT INTO work_institutions (work_id, institution_id) "
                "VALUES (:w, :i) ON CONFLICT DO NOTHING"), {"w": oa_id, "i": iid})
            db.execute(text(
                "UPDATE institutions SET corpus_degree = corpus_degree + 1 "
                "WHERE id = :i"), {"i": iid})

    for t in w.get("topics") or []:
        tid = short_id(t.get("id"))
        if not tid:
            continue
        db.execute(text(
            "INSERT INTO topics (id, display_name, subfield, field, domain, "
            " corpus_degree, idf) VALUES (:i, :n, :s, :f, :d, 0, 1.0) "
            "ON CONFLICT (id) DO NOTHING"),
            {"i": tid, "n": t.get("display_name"),
             "s": (t.get("subfield") or {}).get("display_name"),
             "f": (t.get("field") or {}).get("display_name"),
             "d": (t.get("domain") or {}).get("display_name")})
        db.execute(text(
            "INSERT INTO work_topics (work_id, topic_id, score) "
            "VALUES (:w, :t, :s) ON CONFLICT DO NOTHING"),
            {"w": oa_id, "t": tid, "s": float(t.get("score") or 0.0)})
        db.execute(text(
            "UPDATE topics SET corpus_degree = corpus_degree + 1 WHERE id = :t"),
            {"t": tid})

    return oa_id


def _local_work(db: Session, title: str | None) -> str:
    """A UL... local work: content that exists solely because a user uploaded
    it. Ids come from work_local_id_seq and are NEVER reused (spec B6: the
    engine has no transactional memory; a reused id would inherit phantom
    edges from an abandoned confirm)."""
    n = db.execute(text("SELECT nextval('work_local_id_seq')")).scalar_one()
    wid = f"L{n}"
    db.execute(text(
        "INSERT INTO works (id, title, cited_by_count, is_oa, is_stub, "
        " ref_count, in_corpus_cited_by, source) "
        "VALUES (:id, :title, 0, false, false, 0, 0, 'user_upload')"),
        {"id": wid, "title": title or "(untitled upload)"})
    return wid


