def confirm_upload(db: Session, upload: Upload) -> dict:
    """Apply a reviewed draft. Returns counts for the response. Raises
    ConfirmError with a specific reason on rejection."""
    if upload.status not in ("draft", "engine_pending"):
        raise ConfirmError(f"Upload is {upload.status!r}; nothing to confirm.")

    refs = (db.query(UploadReference)
            .filter(UploadReference.upload_id == upload.id,
                    UploadReference.decision == "accept")
            .order_by(UploadReference.idx).all())
    if not refs:
        raise ConfirmError(
            "No accepted references. Tick at least one entry (DOI/arXiv "
            "matches arrive ticked; everything else needs an explicit tick).")
    if len(refs) > MAX_CONFIRM_REFERENCES:
        raise ConfirmError(
            f"{len(refs)} accepted references exceeds the "
            f"{MAX_CONFIRM_REFERENCES} cap. Reject some entries first.")

    oa = OpenAlex()

    # ---- Postgres transaction: every relational fact, then the version bump.
    own_id = upload.work_id
    n_added = 0
    if own_id is None:
        resolved = (db.get(Work, upload.resolved_work_id)
                    if upload.resolved_work_id else None)
        # Belt over D11: never adopt ANOTHER profile's uploaded local as this
        # upload's own paper, even from a stale draft resolution.
        if resolved is not None and resolved.source == "user_upload":
            owner = db.execute(text(
                "SELECT count(*) FROM uploads WHERE work_id = :w "
                "AND profile_id = :p"), {"w": resolved.id,
                                         "p": upload.profile_id}).scalar_one()
            if not owner:
                resolved = None
        if resolved is not None:
            own_id = resolved.id
        elif upload.resolved_openalex_id:
            own_id = materialise_openalex_work(db, oa, upload.resolved_openalex_id)
            if own_id:
                n_added += 1
        if own_id is None:
            own_id = _local_work(db, upload.title)
            n_added += 1
    upload.work_id = own_id

    ref_work_ids: dict[int, str] = {}
    skipped_unavailable = 0
    for r in refs:
        wid = r.work_id
        if wid is None and r.resolved_openalex_id:
            wid = materialise_openalex_work(db, oa, r.resolved_openalex_id)
            if wid:
                r.work_id = wid
                n_added += 1
            else:
                skipped_unavailable += 1
        if wid:
            ref_work_ids[r.idx] = wid

    if not ref_work_ids:
        db.rollback()
        raise ConfirmError(
            "None of the accepted references could be materialised "
            "(OpenAlex unreachable). Try again later.")

    # citations + denormalised counters. rowcount distinguishes rows this
    # confirm CREATED from pre-existing corpus citations (a corpus paper
    # uploaded by its own author may already carry some) -- undo may only
    # delete what confirm created.
    created_citation: dict[int, bool] = {}
    for r in refs:
        wid = ref_work_ids.get(r.idx)
        if not wid:
            continue
        res = db.execute(text(
            "INSERT INTO citations (src_id, dst_id) VALUES (:s, :d) "
            "ON CONFLICT DO NOTHING"), {"s": own_id, "d": wid})
        created = bool(res.rowcount)
        created_citation[r.idx] = created
        r.created_citation = created
        if created:
            db.execute(text(
                "UPDATE works SET in_corpus_cited_by = in_corpus_cited_by + 1 "
                "WHERE id = :d"), {"d": wid})
    db.execute(text("UPDATE works SET ref_count = :n WHERE id = :w"),
               {"n": len(ref_work_ids), "w": own_id})

    # graph edges: cites/cited_by with the CITED work's epoch factor, plus
    # entity edges for newly materialised works (parity with build_graph.py).
    years = {r[0]: r[1] for r in db.execute(text(
        "SELECT id, year FROM works WHERE id = ANY(:ids)"),
        {"ids": list(ref_work_ids.values())}).all()}
    own_node = work_node(own_id)
    edges: list[Edge] = []
    for wid in ref_work_ids.values():
        f = epoch_factor(years.get(wid))
        edges.append(Edge(own_node, work_node(wid), W["cites"] * f,
                          config.BASELINE_CONTEXT, "cites"))
        edges.append(Edge(work_node(wid), own_node, W["cited_by"] * f,
                          config.BASELINE_CONTEXT, "cited_by"))
    fresh = [w for w in set(ref_work_ids.values()) | {own_id}
             if db.execute(text(
                 "SELECT count(*) FROM graph_edges WHERE src = :n"),
                 {"n": work_node(w)}).scalar_one() == 0]
    for wid in fresh:
        edges.extend(_entity_edges_for(db, wid))
    _persist_edges(db, edges)

    # trust + trust_sources (survivorship: the trust row outlives this upload
    # only through other sources or by having been hand-added -- undo logic).
    profile_id = upload.profile_id
    for r in refs:
        wid = ref_work_ids.get(r.idx)
        if not wid:
            continue
        existing = db.get(Trust, {"profile_id": profile_id, "work_id": wid})
        if existing is None:
            db.add(Trust(profile_id=profile_id, work_id=wid,
                         strength=int(r.strength), is_distrust=False))
            db.flush()
        db.execute(text(
            "INSERT INTO trust_sources (profile_id, work_id, upload_id, "
            " created_trust) VALUES (:p, :w, :u, :c) ON CONFLICT DO NOTHING"),
            {"p": profile_id, "w": wid, "u": upload.id,
             "c": existing is None})

    upload.n_added = n_added
    upload.status = "applying"
    version = bump_graph_version(db)
    db.commit()

    # ---- Engine push, OUTSIDE the transaction: idempotent, reconciled. The
    # edges are read BACK from graph_edges (not the in-memory list), so the
    # engine receives exactly the post-merge weights the table holds.
    committed_edges = _upload_graph_edges(db, upload)
    trust_edges = _trust_edges_for_profile(db, profile_id)
    ok = push_upload_edges(db, committed_edges + trust_edges)
    upload.status = "confirmed" if ok else "engine_pending"
    db.commit()
    if ok:
        # The profile's trust edges just went in with the batch; the next read
        # must not re-put them one by one.
        _mark_profile_seeded(db, profile_id)

    services.invalidate_scores(profile_id)
    log.info("confirm %s: own=%s refs=%d added=%d skipped=%d engine_ok=%s "
             "version=%d", upload.id, own_id, len(ref_work_ids), n_added,
             skipped_unavailable, ok, version)
    return {
        "status": upload.status,
        "work_id": own_id,
        "n_cited": len(ref_work_ids),
        "n_added": n_added,
        "n_skipped_unavailable": skipped_unavailable,
        "n_trust": len(ref_work_ids),
    }


def _mark_profile_seeded(db: Session, profile_id: str) -> None:
    from .models import Profile
    prof = db.get(Profile, profile_id)
    if prof is not None:
        ranking.mark_seeded(db, prof)


def _trust_edges_for_profile(db: Session, profile_id: str) -> list[Edge]:
    """The profile's FULL trust edge set (idempotent to re-put)."""
    ego = profile_node(profile_id)
    out = []
    for t in db.query(Trust).filter(Trust.profile_id == profile_id).all():
        w = (config.DISTRUST_WEIGHT if t.is_distrust
             else config.TRUST_STRENGTH_SCALE.get(t.strength, 0.7))
        out.append(Edge(ego, work_node(t.work_id), w, config.AGGREGATE, "trusts"))
    return out


def push_upload_edges(db: Session, edges: list[Edge]) -> bool:
    """One mr_put_edges batch. True on success. Failure is contained: the
    Postgres truth is already committed and reconciliation repairs the engine."""
    if not edges:
        return True
    try:
        t0 = time.time()
        MeritRank(db.connection()).put_edges(edges)
        db.commit()
        log.info("engine push: %d edges in %.2fs", len(edges), time.time() - t0)
        return True
    except Exception as e:  # noqa: BLE001 - contained by design
        db.rollback()
        log.warning("engine push failed (%d edges): %s", len(edges), str(e)[:200])
        return False


# ---------------------------------------------------------------------------
# Undo (spec): delete this upload's trust_sources; delete each trust row only
# when no other source survives AND this upload created it; delete the
# citations/graph_edges rows the confirm created; one batched mr_delete_edge
# pass (propagates to all contexts per call); bump graph_meta.version. Engine
# node NAMES linger in the registry until restart -- harmless, documented.
# ---------------------------------------------------------------------------

def undo_upload(db: Session, upload: Upload) -> dict:
    profile_id = upload.profile_id
    own_id = upload.work_id
    own_is_local = bool(own_id) and (db.execute(text(
        "SELECT source FROM works WHERE id = :i"), {"i": own_id}
    ).scalar() == "user_upload")

    # 1. Trust survivorship.
    sources = db.execute(text(
        "SELECT work_id, created_trust FROM trust_sources WHERE upload_id = :u"),
        {"u": upload.id}).all()
    db.execute(text("DELETE FROM trust_sources WHERE upload_id = :u"),
               {"u": upload.id})
    n_trust_removed = 0
    for wid, created in sources:
        if not created:
            continue  # hand-added (or another upload created it): survives us
        survivors = db.execute(text(
            "SELECT count(*) FROM trust_sources "
            "WHERE profile_id = :p AND work_id = :w"),
            {"p": profile_id, "w": wid}).scalar_one()
        if survivors == 0:
            db.execute(text(
                "DELETE FROM trust WHERE profile_id = :p AND work_id = :w"),
                {"p": profile_id, "w": wid})
            n_trust_removed += 1

    # 2. Citations + graph edges this confirm created.
    created_refs = db.query(UploadReference).filter(
        UploadReference.upload_id == upload.id,
        UploadReference.created_citation.is_(True),
        UploadReference.work_id.isnot(None)).all() if own_id else []
    edge_pairs: list[tuple[str, str]] = []
    for r in created_refs:
        db.execute(text(
            "DELETE FROM citations WHERE src_id = :s AND dst_id = :d"),
            {"s": own_id, "d": r.work_id})
        db.execute(text(
            "UPDATE works SET in_corpus_cited_by = "
            "greatest(in_corpus_cited_by - 1, 0) WHERE id = :d"),
            {"d": r.work_id})
        edge_pairs.append((work_node(own_id), work_node(r.work_id)))
        edge_pairs.append((work_node(r.work_id), work_node(own_id)))
    if own_is_local:
        # A UL local exists solely because of this upload: every edge touching
        # it goes, and so does the works row itself ("zero residue").
        rows = db.execute(text(
            "SELECT src, dst FROM graph_edges WHERE src = :n OR dst = :n"),
            {"n": work_node(own_id)}).all()
        edge_pairs.extend((r[0], r[1]) for r in rows)
    edge_pairs = list(dict.fromkeys(edge_pairs))
    for src, dst in edge_pairs:
        db.execute(text(
            "DELETE FROM graph_edges WHERE src = :s AND dst = :d"),
            {"s": src, "d": dst})

    # 3. The upload row (CASCADE takes upload_references + any source leftovers)
    #    and, for a local paper, the works row.
    db.delete(upload)
    if own_is_local:
        db.execute(text("DELETE FROM works WHERE id = :i"), {"i": own_id})

    # 4. Trust edges for removed trust rows must leave the engine too.
    removed_trust_edges = [
        (profile_node(profile_id), work_node(wid))
        for wid, created in sources if created
        # (deleted above only when no survivors; re-deriving that set here
        #  would race with the deletes, so recompute from the trust table)
        and db.execute(text(
            "SELECT count(*) FROM trust WHERE profile_id = :p AND work_id = :w"),
            {"p": profile_id, "w": wid}).scalar_one() == 0
    ]

    version = bump_graph_version(db)
    db.commit()

    # 5. One batched engine delete pass, outside the transaction. Each
    #    mr_delete_edge propagates to every context in a single call
    #    (verified, spec B2-method). Failures are tolerable: the next full
    #    rebuild regenerates the engine from the (already-clean) tables.
    mr = MeritRank(db.connection())
    n_engine_deleted = 0
    for src, dst in edge_pairs + removed_trust_edges:
        try:
            mr.delete_edge(src, dst, config.AGGREGATE)
            n_engine_deleted += 1
        except Exception as e:  # noqa: BLE001
            log.warning("undo: mr_delete_edge(%s, %s) failed: %s",
                        src, dst, str(e)[:120])
    db.commit()

    ranking.forget_seeded(profile_id)
    services.invalidate_scores(profile_id)
    log.info("undo %s: %d graph edges, %d trust rows, %d engine deletes, "
             "local=%s version=%d", upload.id, len(edge_pairs),
             n_trust_removed, n_engine_deleted, own_is_local, version)
    return {
        "n_edges_removed": len(edge_pairs),
        "n_trust_removed": n_trust_removed,
        "n_engine_deleted": n_engine_deleted,
        "removed_local_work": own_is_local,
    }


# ---------------------------------------------------------------------------
# Reconciliation: engine_pending uploads are repaired in the background.
# ---------------------------------------------------------------------------

_RECONCILE_INTERVAL = 60.0
_reconcile_started = threading.Event()


def reconcile_pending(db: Session) -> int:
    """Re-push edges for every engine_pending upload. Returns how many were
    repaired. Idempotent: put semantics overwrite identical weights."""
    pending = db.query(Upload).filter(Upload.status == "engine_pending").all()
    repaired = 0
    for upload in pending:
        edges = _upload_graph_edges(db, upload)
        trust_edges = _trust_edges_for_profile(db, upload.profile_id)
        if push_upload_edges(db, edges + trust_edges):
            upload.status = "confirmed"
            db.commit()
            _mark_profile_seeded(db, upload.profile_id)
            services.invalidate_scores(upload.profile_id)
            repaired += 1
    return repaired


def _upload_graph_edges(db: Session, upload: Upload) -> list[Edge]:
    """Recover the upload's edges FROM THE COMMITTED graph_edges ROWS -- the
    derived layer is re-derivable from the layer above it, never recomputed
    from scratch (it might drift).

    Scope: edges touching the uploaded paper's node (that covers every
    cites/cited_by pair, since one endpoint is always the paper) plus edges
    touching works this upload MATERIALISED from OpenAlex (their entity edges
    have no endpoint on the paper). NOT every reference node: the first cut
    swept every edge touching the cited works, and citing eight top-cited
    corpus papers dragged 5,412 pre-existing edges into an 8-reference push.
    Idempotent either way, but 200x the traffic for nothing."""
    if not upload.work_id:
        return []
    own = work_node(upload.work_id)
    nodes = {own}
    for r in db.query(UploadReference).filter(
            UploadReference.upload_id == upload.id,
            UploadReference.work_id.isnot(None),
            UploadReference.resolved_openalex_id.isnot(None)).all():
        nodes.add(work_node(r.work_id))
    rows = db.execute(text(
        "SELECT src, dst, weight, context, relation FROM graph_edges "
        "WHERE src = ANY(:n) OR dst = ANY(:n)"), {"n": list(nodes)}).all()
    return [Edge(r[0], r[1], float(r[2]), r[3], r[4]) for r in rows]


def _sweep_loop() -> None:
    from .db import SessionLocal
    while True:
        time.sleep(_RECONCILE_INTERVAL)
        try:
            with SessionLocal() as db:
                n = reconcile_pending(db)
                if n:
                    log.info("reconcile sweep repaired %d upload(s)", n)
        except Exception:  # noqa: BLE001 - the sweep must survive anything
            log.warning("reconcile sweep failed", exc_info=True)


def start_reconcile_sweep() -> None:
    if _reconcile_started.is_set():
        return
    _reconcile_started.set()
    threading.Thread(target=_sweep_loop, name="upload-reconcile",
                     daemon=True).start()
